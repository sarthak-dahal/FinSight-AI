"""Answer every question in seed_questions.json end to end and score the answers.

Writes reports/evaluation_report.md (summary + every answer for human review) and the raw
run to data/evaluation/runs/<timestamp>.json.

Usage: uv run scripts/run_evaluation.py [--model gemma3:12b] [--ids sq_001 sq_020]
Needs Ollama running. ~30 s per question with gemma3:27b.
"""

import argparse
import json
import time
from datetime import datetime

from finsight.evaluation.answer_scoring import score_answer
from finsight.reasoning.answerer import Answerer
from finsight.reasoning.llm import LLMClient
from finsight.retrieval.common import PROJECT_DIR

QUESTIONS = PROJECT_DIR / "data" / "evaluation" / "seed_questions.json"
RUNS = PROJECT_DIR / "data" / "evaluation" / "runs"
REPORT = PROJECT_DIR / "reports" / "evaluation_report.md"


def pct(values):
    values = [v for v in values if v is not None]
    return f"{sum(values) / len(values):.0%} ({sum(1 for v in values if v)}/{len(values)})" if values else "n/a"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model")
    ap.add_argument("--ids", nargs="+")
    args = ap.parse_args()

    questions = json.loads(QUESTIONS.read_text())
    if args.ids:
        questions = [q for q in questions if q["id"] in args.ids]

    answerer = Answerer(llm=LLMClient(model=args.model))
    answerer.llm.check()
    rows, t0 = [], time.time()
    for i, q in enumerate(questions, 1):
        a = answerer.ask(q["question"])
        s = score_answer(q, a)
        rows.append({"q": q, "a": a, "s": s})
        mark = "PASS" if s["passed"] else "FAIL"
        print(f"[{i:>2}/{len(questions)}] {mark} {q['id']} {a.seconds:5.1f}s  {q['question'][:60]}", flush=True)

    model = answerer.llm.model
    elapsed = time.time() - t0
    summary = {
        "passed": pct([r["s"]["passed"] for r in rows]),
        "key figures stated": pct([r["s"]["figures"] == 1.0 if r["s"]["figures"] is not None else None for r in rows]),
        "abstained correctly": pct([r["s"]["abstain_ok"] for r in rows]),
        "cited (valid citations)": pct([r["s"]["cited"] for r in rows if not r["a"].abstained]),
        "answer passage retrieved": pct([r["s"]["retrieved_answer"] for r in rows]),
        "answer passage cited": pct([r["s"]["grounded"] for r in rows]),
    }

    stamp = datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [
        "# FinSight AI — Answer Evaluation", "",
        f"Run: {stamp} · model `{model}` · {len(rows)} questions · {elapsed / 60:.1f} min "
        f"({elapsed / len(rows):.0f} s/question)", "",
        "Generated by `scripts/run_evaluation.py`. Checks are automatic (see "
        "`src/finsight/evaluation/answer_scoring.py`); narrative quality needs human review below.", "",
        "## Summary", "", "| Check | Result |", "|---|---|",
        *[f"| {k} | {v} |" for k, v in summary.items()], "",
        "## By question", "",
        "| ID | Type | Pass | Figures | Abstain OK | Cited | Retrieved | Grounded | Missing figures |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    yn = lambda v: "–" if v is None else ("✅" if v else "❌")  # noqa: E731
    for r in rows:
        q, s = r["q"], r["s"]
        fig = "–" if s["figures"] is None else f"{s['figures']:.0%}"
        lines.append(f"| {q['id']} | {q['answer_type']} | {yn(s['passed'])} | {fig} | {yn(s['abstain_ok'])} | "
                     f"{yn(s['cited'])} | {yn(s['retrieved_answer'])} | {yn(s['grounded'])} | "
                     f"{', '.join(map(str, s['missing_figures'])) or ''} |")
    lines += ["", "## Answers", ""]
    for r in rows:
        q, a = r["q"], r["a"]
        lines += [f"### {q['id']} — {'PASS' if r['s']['passed'] else 'FAIL'}", "",
                  f"**Q:** {q['question']}", "", f"**Expected:** {q['expected_answer']}", "",
                  f"**FinSight:** {a.text}", "", "<details><summary>Sources cited</summary>", "",
                  *[f"- {src}" for src in a.sources()], "", "</details>", ""]
    REPORT.write_text("\n".join(lines))

    RUNS.mkdir(parents=True, exist_ok=True)
    run_file = RUNS / f"{datetime.now():%Y%m%d-%H%M%S}-{model.replace(':', '_')}.json"
    run_file.write_text(json.dumps({
        "model": model, "time": stamp, "summary": summary,
        "results": [{"id": r["q"]["id"], "answer": r["a"].text, "citations": r["a"].citations,
                     "cited_chunks": r["a"].cited_chunks, "seconds": round(r["a"].seconds, 1), **r["s"]}
                    for r in rows],
    }, indent=2))

    print("\n" + "\n".join(f"{k:<26} {v}" for k, v in summary.items()))
    print(f"\nReport: {REPORT.relative_to(PROJECT_DIR)}  Run: {run_file.relative_to(PROJECT_DIR)}")


if __name__ == "__main__":
    main()
